const categoryContainer = document.getElementById("categories");
const topicPanel = document.getElementById("topicPanel");
const topicList = document.getElementById("topicList");
const selectedPanel = document.getElementById("selectedTopic");

Object.entries(allCategories).forEach(([key, category]) => {
  const button = document.createElement("button");
  button.className = "category-card";
  button.innerHTML = `<span class="category-icon">${category.icon}</span>
  <span class="category-name">${category.label}</span>
  <span class="category-total">${category.topics.length} prompts</span>`;

  button.addEventListener("click", () => showCategoryTopics(key));
  categoryContainer.appendChild(button);

});

function showCategoryTopics(categoryKey) {

  const category = allCategories[categoryKey];

  document.querySelectorAll(".category-card").forEach((button, index) => button.classList.toggle("active", Object.keys(allCategories)[index] === categoryKey));
  document.getElementById("categoryLabel").textContent = `${category.label.toUpperCase()} / PROMPTS`;
  document.getElementById("topicCount").textContent = `${category.topics.length} AVAILABLE`;
  topicPanel.classList.remove("is-hidden");
  topicList.replaceChildren();

  category.topics.forEach((topic) => {

    const button = document.createElement("button");
    button.className = "topic-option";
    button.textContent = topic;
    button.addEventListener("click", () => showTopic(categoryKey, topic));
    topicList.appendChild(button);
  });

  topicPanel.scrollIntoView({ behavior: "smooth", block: "start" });
}

function showTopic(categoryKey, topic) {
  const category = allCategories[categoryKey];
  selectedPanel.classList.remove("is-hidden");

  selectedPanel.innerHTML = `<div class="selected-card">
  <p class="eyebrow">YOUR SELECTED TOPIC / ${category.label.toUpperCase()}</p>
  <h2>“${topic}”</h2><span class="duration-label">SPEAKING TIME</span>
    <div class="duration-options">
      <button class="duration-option" data-duration="60">1 min</button>
      <button class="duration-option selected" data-duration="120">2 min</button>
      <button class="duration-option" data-duration="300">5 min</button>
      <button class="duration-option" data-duration="600">10 min</button>
    </div>
  <button id="startSession" class="start-session">Continue to practice →</button>
  </div>`;

  selectedPanel.querySelectorAll(".duration-option").forEach((button) => button.addEventListener("click", () => {
    selectedPanel.querySelectorAll(".duration-option").forEach((item) => item.classList.remove("selected"));
    button.classList.add("selected");
  })
);

  selectedPanel.querySelector("#startSession").addEventListener("click", () => {
    const duration = Number(selectedPanel.querySelector(".duration-option.selected").dataset.duration);
    localStorage.setItem("selectedTopic", JSON.stringify({ category: category.label, topic, duration }));
    window.location.href = "practice.html";
  });
  selectedPanel.scrollIntoView({ behavior: "smooth", block: "center" });
}

document.getElementById("randomBtn").addEventListener("click", () => {
  const categoryKeys = Object.keys(allCategories);
  const categoryKey = categoryKeys[Math.floor(Math.random() * categoryKeys.length)];
  const topics = allCategories[categoryKey].topics;
  showTopic(categoryKey, topics[Math.floor(Math.random() * topics.length)]);
});
